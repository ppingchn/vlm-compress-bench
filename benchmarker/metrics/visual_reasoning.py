"""
Visual Reasoning metric evaluator module for VLM compression benchmarking.

This module evaluates visual reasoning performance on the GQA dataset using exact match
accuracy on normalized short answers generated by a Visual Language Model (VLM).

Output snapshot schema for 'visual_reasoning':
{
    "accuracy": float,
    "consistency": float | None,
    "validity": float | None,
    "plausibility": float | None,
    "dataset": "GQA",
    "num_samples": int,
}
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional, Union

from tqdm import tqdm

from benchmarker.metrics.base import BaseMetricEvaluator
from benchmarker.utils import (
    extract_short_answer,
    generate_text,
    normalize_answer,
)

logger = logging.getLogger(__name__)

#: Default prompt format for GQA visual reasoning evaluation.
PROMPT_TEMPLATE: str = (
    "Question: {question}\n"
    "Answer the question using a single word or phrase."
)


class VisualReasoningEvaluator(BaseMetricEvaluator):
    """Evaluator for visual reasoning capabilities using the GQA dataset.

    This evaluator measures exact match accuracy on visual reasoning questions,
    normalizing model output and ground truth answers. Consistency, validity,
    and plausibility metrics are set to ``None`` by default as they require specialized
    GQA evaluation scripts and ontology annotations, but consistency will be computed
    if question group metadata is present in the dataset samples.
    """

    @property
    def group_name(self) -> str:
        """Return the schema metric group key."""
        return "visual_reasoning"

    def evaluate(
        self,
        model: Any,
        processor: Any,
        *,
        device: str = "cuda",
        max_samples: Optional[int] = None,
        batch_size: int = 1,
        max_new_tokens: int = 128,
        **kwargs: Any,
    ) -> Dict[str, Any]:
        """Run visual reasoning evaluation on the GQA dataset.

        Args:
            model: A HuggingFace-compatible VLM model (must support ``model.generate()``).
            processor: The paired processor/tokenizer for handling image and text inputs.
            device: Torch device string (e.g., ``"cuda"``, ``"cpu"``).
            max_samples: Optional maximum number of samples to evaluate.
            batch_size: Batch size for inference (defaults to 1).
            max_new_tokens: Maximum new tokens to generate per question.
            **kwargs: Additional evaluator-specific options:
                - ``dataset_name`` (str): HuggingFace dataset path (default: ``"lmms-lab/GQA"``).
                - ``dataset`` (Any): Pre-loaded dataset or sample iterable.
                - ``split`` (str): Dataset split to load (default: ``"validation"``).
                - ``dataset_label`` (str): Dataset string label for snapshot (default: ``"GQA"``).

        Returns:
            Dict[str, Any]: A dictionary matching the 'visual_reasoning' snapshot schema:
                {
                    "accuracy": float,
                    "consistency": float | None,
                    "validity": float | None,
                    "plausibility": float | None,
                    "dataset": str,
                    "num_samples": int,
                }
        """
        dataset = kwargs.get("dataset")
        dataset_name = kwargs.get("dataset_name", "lmms-lab/GQA")
        split = kwargs.get("split", "validation")
        dataset_label = kwargs.get("dataset_label", "GQA")

        # Load dataset if not pre-loaded
        if dataset is None:
            dataset = self._load_dataset_safe(dataset_name, split)

        if dataset is None or (hasattr(dataset, "__len__") and len(dataset) == 0):
            logger.warning("[%s] No dataset samples available for evaluation.", self.group_name)
            results: Dict[str, Any] = {
                "accuracy": 0.0,
                "consistency": None,
                "validity": None,
                "plausibility": None,
                "dataset": dataset_label,
                "num_samples": 0,
            }
            self._log_done(results)
            return results

        # Limit maximum samples if specified
        if max_samples is not None and max_samples > 0:
            if hasattr(dataset, "select"):
                num_samples = min(len(dataset), max_samples)
                dataset = dataset.select(range(num_samples))
            elif isinstance(dataset, (list, tuple)):
                dataset = dataset[:max_samples]
            else:
                try:
                    import itertools
                    dataset = list(itertools.islice(dataset, max_samples))
                except Exception as err:
                    logger.debug("Failed to slice dataset: %s", err)

        total_samples = len(dataset) if hasattr(dataset, "__len__") else max_samples or 0
        self._log_start(total_samples)

        correct_count = 0
        total_processed = 0
        group_results: Dict[str, List[bool]] = {}

        for sample in tqdm(dataset, desc=f"Evaluating {self.group_name} ({dataset_label})"):
            try:
                # Extract image
                image = self._extract_field(sample, ["image", "img", "visual"])
                if image is None:
                    logger.warning("[%s] Sample missing image, skipping.", self.group_name)
                    continue

                # Extract question
                question = self._extract_field(sample, ["question", "prompt", "q", "text"])
                if not question:
                    logger.warning("[%s] Sample missing question, skipping.", self.group_name)
                    continue

                # Extract ground truth answer
                gt_answer = self._extract_field(
                    sample, ["answer", "label", "gt_answer", "gt", "target", "fullAnswer"]
                )
                if gt_answer is None:
                    logger.warning("[%s] Sample missing ground truth answer, skipping.", self.group_name)
                    continue

                # Construct prompt
                prompt = PROMPT_TEMPLATE.format(question=question)

                # Generate model text
                raw_output = generate_text(
                    model,
                    processor,
                    image=image,
                    prompt=prompt,
                    device=device,
                    max_new_tokens=max_new_tokens,
                )

                # Extract short answer (up to 3 words) and normalize
                short_pred = extract_short_answer(raw_output, max_words=3)
                norm_pred = normalize_answer(short_pred)

                # Normalize ground truth answer(s)
                gt_norms = self._normalize_gt(gt_answer)

                # Compare exact match after normalization
                is_correct = norm_pred in gt_norms
                if is_correct:
                    correct_count += 1
                total_processed += 1

                # Track question groups for consistency metric if group ID exists
                group_id = self._extract_field(sample, ["group", "groupId", "group_id", "fullId"])
                if group_id is not None:
                    group_key = str(group_id)
                    if group_key not in group_results:
                        group_results[group_key] = []
                    group_results[group_key].append(is_correct)

            except Exception as exc:
                logger.error("[%s] Error processing individual sample: %s", self.group_name, exc, exc_info=True)
                continue

        accuracy = float(correct_count / total_processed) if total_processed > 0 else 0.0

        # Calculate consistency if group information was collected
        consistency: Optional[float] = None
        if group_results:
            consistent_groups = sum(1 for res in group_results.values() if all(res))
            consistency = float(consistent_groups / len(group_results))

        validity: Optional[float] = None
        plausibility: Optional[float] = None

        results: Dict[str, Any] = {
            "accuracy": accuracy,
            "consistency": consistency,
            "validity": validity,
            "plausibility": plausibility,
            "dataset": dataset_label,
            "num_samples": total_processed,
        }

        self._log_done(results)
        return results

    @staticmethod
    def _load_dataset_safe(dataset_name: str, split: str) -> Any:
        """Safely load HuggingFace dataset with fallback splits and clear error messages.

        Args:
            dataset_name: Path or identifier for the dataset on HuggingFace Hub.
            split: Preferred dataset split name.

        Returns:
            The loaded HuggingFace dataset split object.

        Raises:
            ImportError: If ``datasets`` is not installed.
            ValueError: If dataset loading fails across all attempt splits.
        """
        try:
            from datasets import load_dataset
        except ImportError as err:
            logger.error("HuggingFace 'datasets' library is required to load '%s'", dataset_name)
            raise ImportError(
                "The 'datasets' package is required for VisualReasoningEvaluator. "
                "Please install it via `pip install datasets`."
            ) from err

        splits_to_try = [split, "validation", "testdev_balanced", "testdev", "test"]
        seen = set()
        unique_splits = [s for s in splits_to_try if not (s in seen or seen.add(s))]

        for s in unique_splits:
            try:
                logger.info("Attempting to load dataset '%s' (split='%s')...", dataset_name, s)
                ds = load_dataset(dataset_name, split=s)
                logger.info("Successfully loaded dataset '%s' (split='%s', count=%d)", dataset_name, s, len(ds))
                return ds
            except Exception as err:
                logger.debug("Could not load dataset '%s' with split '%s': %s", dataset_name, s, err)

        # Fallback attempt without explicit split
        try:
            ds = load_dataset(dataset_name)
            if isinstance(ds, dict) or hasattr(ds, "keys"):
                first_split = next(iter(ds.keys()))
                logger.info("Loaded default split '%s' for dataset '%s'", first_split, dataset_name)
                return ds[first_split]
            return ds
        except Exception as err:
            logger.error("Failed to load dataset '%s': %s", dataset_name, err)
            raise ValueError(f"Failed to load dataset '{dataset_name}': {err}") from err

    @staticmethod
    def _extract_field(sample: Any, candidate_keys: List[str]) -> Any:
        """Extract a field from a sample dict or object using candidate key names.

        Args:
            sample: The dataset item (dictionary or object).
            candidate_keys: Priority list of attribute or dictionary keys to search.

        Returns:
            The value of the first matching field, or ``None`` if not found.
        """
        if isinstance(sample, dict):
            for key in candidate_keys:
                if key in sample and sample[key] is not None:
                    return sample[key]
        else:
            for key in candidate_keys:
                if hasattr(sample, key):
                    val = getattr(sample, key)
                    if val is not None:
                        return val
        return None

    @staticmethod
    def _normalize_gt(gt_answer: Union[str, List[str], tuple, set]) -> List[str]:
        """Normalize ground truth answer or collection of ground truth answers.

        Args:
            gt_answer: Ground truth string or iterable of acceptable answer strings.

        Returns:
            List of normalized ground truth answer strings.
        """
        if isinstance(gt_answer, (list, tuple, set)):
            return [normalize_answer(str(ans)) for ans in gt_answer if ans is not None]
        return [normalize_answer(str(gt_answer))]
